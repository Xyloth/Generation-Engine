    def stream_chat(self, body: dict[str, Any]) -> None:
        slug = str(body.get("slug") or "")
        user_message = str(body.get("message") or "").strip()
        if not slug or not user_message:
            self.send_error_json(400, "Missing chat message.")
            return
        append_conversation_message(slug, "user", user_message, {"kind": "chat"})
        self.send_response(200)
        self.send_header("content-type", "text/plain; charset=utf-8")
        self.send_header("cache-control", "no-store")
        self.send_header("connection", "close")
        self.end_headers()
        chunks: list[str] = []

        def write_chunk(text: str) -> None:
            if not text:
                return
            chunks.append(text)
            try:
                self.wfile.write(text.encode("utf-8"))
                self.wfile.flush()
            except (BrokenPipeError, ConnectionResetError, ConnectionAbortedError):
                raise ClientDisconnected()

        try:
            for piece in chat_stream(slug, user_message):
                write_chunk(piece)
            assistant_text = "".join(chunks)
            _clean, marker = extract_draft_marker(assistant_text)
            metadata = {"kind": "draft" if marker else "chat"}
            if marker:
                metadata["draft"] = marker
            append_conversation_message(slug, "assistant", assistant_text, metadata)
        except ClientDisconnected:
            return
        except Exception as exc:
            message = f"\n\n[Generation error: {exc}]\n"
            write_chunk(message)
            append_conversation_message(slug, "assistant", message.strip(), {"kind": "error"})

