def send_bug_report_email(subject: str, body: str) -> dict[str, Any]:
    smtp = bug_report_smtp_config()
    missing = [key for key in ("host", "from", "username", "password") if not smtp.get(key)]
    if missing:
        raise RuntimeError(
            "Direct bug-report email is not configured. Add bugReport.smtp to config.local.json "
            f"(missing: {', '.join(missing)})."
        )
    recipient = bug_report_recipient()
    msg = EmailMessage()
    msg["From"] = str(smtp["from"])
    msg["To"] = recipient
    msg["Subject"] = subject.strip()[:180] or "Generation Engine bug report"
    msg.set_content(body)
    if smtp.get("ssl"):
        with smtplib.SMTP_SSL(str(smtp["host"]), int(smtp["port"]), timeout=30, context=ssl.create_default_context()) as server:
            server.login(str(smtp["username"]), str(smtp["password"]))
            server.send_message(msg)
    else:
        with smtplib.SMTP(str(smtp["host"]), int(smtp["port"]), timeout=30) as server:
            server.ehlo()
            if smtp.get("starttls"):
                server.starttls(context=ssl.create_default_context())
                server.ehlo()
            server.login(str(smtp["username"]), str(smtp["password"]))
            server.send_message(msg)
    return {"ok": True, "sent": True, "recipient": recipient}


