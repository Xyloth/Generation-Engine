def local_lock_updates(data: dict[str, Any], target: dict[str, Any]) -> dict[str, str]:
    canon = {name: data["canon"][name]["content"] for name in CANON_FILES}
    chapter_id = target["id"]
    title = target["title"]
    summary = first_sentences(target.get("content", ""), 4) or "Summary needed."
    names = extract_names(target.get("content", ""), 8)
    timeline_entry = f"\n\n## Chapter {int(chapter_id)}: {title}\n{summary}\n"
    if f"## Chapter {int(chapter_id)}:" not in canon["timeline"]:
        canon["timeline"] = canon["timeline"].rstrip() + timeline_entry
    if names:
        existing = canon["characters"]
        additions = []
        for name in names:
            if name not in existing:
                additions.append(
                    f"\n## {name}\n- Role: Introduced or referenced in Chapter {int(chapter_id)}. Review and edit.\n- Voice:\n- Goals:\n- Fears:\n- Relationships:\n- Current state:\n"
                )
        if additions:
            canon["characters"] = existing.rstrip() + "\n" + "\n".join(additions)
    canon["arcs"] = canon["arcs"].rstrip() + f"\n\n## Chapter {int(chapter_id)} Movement\n- Proposed after locking: {summary[:260]}\n"
    return canon


def extract_json(text: str) -> str:
    text = text.strip()
    if text.startswith("```"):
        text = re.sub(r"^```(?:json)?", "", text).strip()
        text = re.sub(r"```$", "", text).strip()
    start = text.find("{")
    end = text.rfind("}")
    if start >= 0 and end > start:
        return text[start : end + 1]
    return text


