def research_missing_report(slug: str) -> dict[str, Any]:
    research = load_research(slug)
    claims = research["claims"]
    people = research["people"]
    records = research["records"]
    low_claims = [c for c in claims if c.get("confidence") in {"unsourced", "single-sourced", "contradicted"} or c.get("publish_readiness") in {"blocked", "needs_review"}]
    unsourced_people = [p for p in people if not p.get("source_refs")]
    contradictions = [c for c in claims if c.get("contradicting_sources")]
    overdue = []
    today = datetime.now().date()
    for record in records:
        deadline = str(record.get("deadline") or "")
        if deadline and str(record.get("status")) in {"sent", "acknowledged"}:
            try:
                if datetime.strptime(deadline[:10], "%Y-%m-%d").date() < today:
                    overdue.append(record)
            except Exception:
                pass
    markdown = ["## What's Missing"]
    markdown.append(f"- Low-confidence or blocked claims: {len(low_claims)}")
    markdown.append(f"- Entities without source refs: {len(unsourced_people)}")
    markdown.append(f"- Claims with contradictions: {len(contradictions)}")
    markdown.append(f"- Overdue records requests: {len(overdue)}")
    if low_claims[:8]:
        markdown.append("\n### Claims to strengthen")
        markdown.extend(f"- {c.get('id')}: {c.get('text')} ({c.get('publish_readiness')})" for c in low_claims[:8])
    if overdue:
        markdown.append("\n### Overdue records")
        markdown.extend(f"- {r.get('id')}: {r.get('agency')} due {r.get('deadline')}" for r in overdue)
    markdown.append("\n### Suggested next moves")
    markdown.append("- Add primary records for every allegation involving a living person.")
    markdown.append("- Resolve contradictions before drafting clean export prose.")
    markdown.append("- Turn each major timeline event into at least one sourced claim.")
    return {"markdown": "\n".join(markdown), "lowClaims": low_claims, "unsourcedPeople": unsourced_people, "contradictions": contradictions, "overdueRecords": overdue}


def research_export_review(slug: str) -> dict[str, Any]:
    data = load_book(slug)
    research = data.get("research") or {}
    claims = {claim.get("id"): claim for claim in research.get("claims", [])}
    manuscript = "\n\n".join(chapter.get("content", "") for chapter in data.get("chapters", []) if chapter.get("content", "").strip())
    claim_refs = re.findall(r"\[\[claim:(claim-\d+)\]\]", manuscript)
    unsourced_markers = re.findall(r"\[UNSOURCED:[^\]]+\]", manuscript)
    blocked = [claims[ref] for ref in sorted(set(claim_refs)) if claims.get(ref, {}).get("publish_readiness") == "blocked"]
    high_risk = []
    for claim in claims.values():
        if claim.get("publish_readiness") in {"blocked", "needs_review"} and any("living_person" in blocker for blocker in claim.get("publish_blockers", [])):
            high_risk.append(claim)
    markdown = (
        "## Pre-export Sourcing Review\n\n"
        f"- Cited assertions found: {len(claim_refs)}\n"
        f"- Unsourced markers in manuscript: {len(unsourced_markers)}\n"
        f"- Cited blocked claims: {len(blocked)}\n"
        f"- High defamation-risk passages/claims needing review: {len(high_risk)}\n\n"
    )
    if unsourced_markers:
        markdown += "### Unsourced markers\n" + "\n".join(f"- {item}" for item in unsourced_markers[:20]) + "\n\n"
    if blocked:
        markdown += "### Blocked cited claims\n" + "\n".join(f"- {claim.get('id')}: {claim.get('text')}" for claim in blocked[:20]) + "\n\n"
    return {"markdown": markdown, "citedCount": len(claim_refs), "unsourced": unsourced_markers, "blocked": blocked, "highRisk": high_risk}


def build_prompt(task: str, payload: dict[str, Any], slug: str, chapter_id: str | None = None) -> str:
    if task == "voice_profile":
        return (
            "Generate one editable prose-style descriptor paragraph from these author preferences. "
            "Describe rhythm, dialogue, internal thought, description density, register, and signature moves. "
            "Do not imitate source authors directly. Output markdown only.\n\n"
            f"User preferences: {payload.get('authors', '')}"
        )
    if task == "import":
        return (
            "Import these existing chapters. Return strict JSON with keys title, canon, chapters. "
            "canon must contain markdown strings for world, characters, timeline, arcs, voice_profile. "
            "chapters must be an array of objects with id, title, content. "
            "Infer only from the supplied text and mark uncertain facts as proposed.\n\n"
            f"Book title: {payload.get('title', '')}\n\nImported text:\n{payload.get('raw', '')}"
        )
    data = load_book(slug)
    active_id = pad_id(chapter_id or data["meta"].get("activeChapter", "01"))
    chapter = next((c for c in data["chapters"] if c["id"] == active_id), None)
    if task == "plan":
        return (
            "The user is riffing on the next chapter. Ask 1-3 sharp clarifying questions only if material stakes are unclear, "
            "then propose a practical chapter outline. Output markdown with 'Clarifying Questions' and 'Chapter Outline'.\n\n"
            f"Target chapter: {active_id}\n\n"
            f"Current riff:\n{payload.get('riff', '')}\n\n"
            f"Existing transcript:\n{payload.get('transcript', '')}"
        )
    if task == "draft":
        return (
            "Draft the full chapter now. Output only the chapter prose. No notes, no headings except the chapter title if appropriate.\n\n"
            f"Target chapter: {active_id}\n\n"
            f"Chapter plan:\n{payload.get('plan') or (chapter or {}).get('plan', '')}\n\n"
            f"Riff transcript:\n{payload.get('transcript') or (chapter or {}).get('transcript', '')}"
        )
    if task == "revise":
        return (
            "Apply the user's requested edit to the current chapter. Preserve unchanged sections verbatim where possible. "
            "Output the complete revised chapter text only.\n\n"
            f"Revision request:\n{payload.get('request', '')}\n\n"
            f"Current chapter:\n{payload.get('chapter', '')}"
        )
    if task == "continuity":
        scope = payload.get("scope", "chapter")
        body = (chapter or {}).get("content", "") if scope == "chapter" else "\n\n".join(c["content"] for c in data["chapters"])
        return (
            "Run a continuity check. Return a concise markdown list of discrepancies only. "
            "Flag named-entity inconsistencies, timeline conflicts, broken or abandoned arcs, and character voice drift. "
            "Do not fix anything.\n\n"
            f"Scope: {scope}\n\nText:\n{body}"
        )
    if task == "recap":
        return (
            "Generate a concise recap for returning to the book. Include last locked chapter, current open arcs, and what seems planned next. "
            "Output markdown.\n\n"
            f"Recap type: {payload.get('type', 'session')}\nSection: {payload.get('sectionId', '')}"
        )
    if task == "lock":
        return (
            "Read the locked chapter candidate and propose canon updates. Return strict JSON with keys world, characters, timeline, arcs, voice_profile. "
            "Each value must be the full replacement markdown for that canon file, not a patch. Preserve existing useful text and append/modify only what changed.\n\n"
            f"Chapter {active_id}:\n{payload.get('chapter', '')}"
        )
    return json.dumps(payload)


def propose_lock_deltas(slug: str, chapter_id: str) -> dict[str, Any]:
    data = load_book(slug)
    target = next((c for c in data["chapters"] if c["id"] == pad_id(chapter_id)), None)
