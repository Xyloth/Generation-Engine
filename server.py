def parse_multipart_file(content_type: str, raw: bytes) -> tuple[bytes, str]:
    match = re.search(r"boundary=(?P<boundary>[^;]+)", content_type)
    if not match:
        raise ValueError("Missing multipart boundary.")
    boundary = match.group("boundary").strip('"')
    delimiter = ("--" + boundary).encode("utf-8")
    for part in raw.split(delimiter):
        if b"Content-Disposition" not in part:
            continue
        header_blob, _, body = part.partition(b"\r\n\r\n")
        if not body:
            header_blob, _, body = part.partition(b"\n\n")
        headers = header_blob.decode("utf-8", errors="replace")
        if 'name="audio"' not in headers:
            continue
        filename_match = re.search(r'filename="([^"]+)"', headers)
        filename = filename_match.group(1) if filename_match else "recording.wav"
        return body.strip(b"\r\n-"), filename
    raise ValueError("No audio file field was uploaded.")


def parse_multipart_form(content_type: str, raw: bytes) -> tuple[dict[str, str], dict[str, dict[str, Any]]]:
    match = re.search(r"boundary=(?P<boundary>[^;]+)", content_type)
    if not match:
        raise ValueError("Missing multipart boundary.")
    boundary = match.group("boundary").strip('"')
    delimiter = ("--" + boundary).encode("utf-8")
    fields: dict[str, str] = {}
    files: dict[str, dict[str, Any]] = {}
    for part in raw.split(delimiter):
        if b"Content-Disposition" not in part:
            continue
        header_blob, _, body = part.partition(b"\r\n\r\n")
        if not body:
            header_blob, _, body = part.partition(b"\n\n")
        headers = header_blob.decode("utf-8", errors="replace")
        name_match = re.search(r'name="([^"]+)"', headers)
        if not name_match:
            continue
        name = name_match.group(1)
        filename_match = re.search(r'filename="([^"]*)"', headers)
        content_type_match = re.search(r"(?im)^Content-Type:\s*([^\r\n]+)", headers)
        payload = body.rstrip(b"\r\n-")
        if filename_match and filename_match.group(1):
            files[name] = {
                "filename": filename_match.group(1),
                "content_type": content_type_match.group(1).strip() if content_type_match else "",
                "content": payload,
            }
        else:
            fields[name] = payload.decode("utf-8", errors="replace")
    return fields, files


def transcribe_audio_file(audio_path: Path) -> str:
    exe = find_whisper_executable()
    model = find_whisper_model()
    if not exe or not model:
        raise RuntimeError(
            "Local Whisper is not installed. Add whisper.cpp to runtime/whisper and a ggml model to runtime/whisper/models."
        )
    output_base = audio_path.with_suffix("")
    command = [
        str(exe),
        "-m",
        str(model),
        "-f",
        str(audio_path),
        "-otxt",
        "-of",
        str(output_base),
        "-nt",
    ]
    completed = subprocess.run(
        command,
        capture_output=True,
        text=True,
        timeout=300,
        encoding="utf-8",
        errors="replace",
        **hidden_subprocess_kwargs(),
    )
    if completed.returncode != 0:
        raise RuntimeError((completed.stderr or completed.stdout or "Whisper transcription failed.").strip())
    transcript_path = output_base.with_suffix(".txt")
    text = read_text(transcript_path).strip()
    if not text:
        text = (completed.stdout or "").strip()
    return text.strip()


