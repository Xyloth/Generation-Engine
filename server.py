def anthropic_message(
    slug: str,
    prompt: str,
    model: str,
    max_tokens: int = 4000,
    chapter_id: str | None = None,
) -> str:
    if not CONFIG.api_key:
        raise RuntimeError("Missing ANTHROPIC_API_KEY")
    preflight = get_preflight()
    if active_mode() == "api" and not preflight.api_ok:
        raise RuntimeError(preflight.api_message)
    body = {
        "model": model,
        "max_tokens": max_tokens,
        "system": anthropic_system_blocks(slug, chapter_id),
        "messages": [{"role": "user", "content": prompt}],
    }
    req = urllib.request.Request(
        "https://api.anthropic.com/v1/messages",
        data=json.dumps(body).encode("utf-8"),
        headers={
            "content-type": "application/json",
            "x-api-key": CONFIG.api_key,
            "anthropic-version": "2023-06-01",
        },
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=300) as response:
        data = json.loads(response.read().decode("utf-8"))
    return "".join(block.get("text", "") for block in data.get("content", []) if block.get("type") == "text")


def anthropic_stream(
    slug: str,
    prompt: str,
    model: str,
    max_tokens: int = 12000,
    chapter_id: str | None = None,
) -> Iterable[str]:
    if not CONFIG.api_key:
        raise RuntimeError("Missing ANTHROPIC_API_KEY")
    preflight = get_preflight()
    if active_mode() == "api" and not preflight.api_ok:
        raise RuntimeError(preflight.api_message)
    body = {
        "model": model,
        "max_tokens": max_tokens,
        "stream": True,
        "system": anthropic_system_blocks(slug, chapter_id),
        "messages": [{"role": "user", "content": prompt}],
    }
    req = urllib.request.Request(
        "https://api.anthropic.com/v1/messages",
        data=json.dumps(body).encode("utf-8"),
        headers={
            "content-type": "application/json",
            "x-api-key": CONFIG.api_key,
            "anthropic-version": "2023-06-01",
        },
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=600) as response:
        for raw_line in response:
            line = raw_line.decode("utf-8", errors="replace").strip()
            if not line.startswith("data: "):
                continue
            payload = line[6:]
            if payload == "[DONE]":
                break
            try:
                data = json.loads(payload)
            except json.JSONDecodeError:
                continue
            if data.get("type") == "content_block_delta":
                delta = data.get("delta", {})
                if delta.get("type") == "text_delta":
                    yield delta.get("text", "")
            elif data.get("type") == "error":
                error = data.get("error", {})
                raise RuntimeError(error.get("message", "Anthropic streaming error"))


