def claude_code_stream(
    slug: str,
    prompt: str,
    model: str,
    chapter_id: str | None = None,
) -> Iterable[str]:
    command, stdin_prefix = claude_code_command(model, compose_system_prompt(slug, chapter_id), stream=True)
    process = subprocess.Popen(
        command,
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        encoding="utf-8",
        errors="replace",
        bufsize=1,
        **hidden_subprocess_kwargs(),
    )
    stderr_lines: list[str] = []

    def collect_stderr() -> None:
        assert process.stderr is not None
        for line in process.stderr:
            stderr_lines.append(line)

    stderr_thread = threading.Thread(target=collect_stderr, daemon=True)
    stderr_thread.start()
    try:
        assert process.stdin is not None
        process.stdin.write(stdin_prefix + prompt)
        process.stdin.close()
        assert process.stdout is not None
        prior_text = ""
        started_at = time.time()
        for line in process.stdout:
            if time.time() - started_at > GENERATION_TIMEOUT_SECONDS:
                process.kill()
                raise TimeoutError("Claude Code generation timed out.")
            line = line.strip()
            if not line:
                continue
            try:
                event = json.loads(line)
            except json.JSONDecodeError:
                delta = line
            else:
                delta, prior_text = extract_claude_stream_delta(event, prior_text)
            if delta:
                yield delta
        return_code = process.wait(timeout=30)
        if return_code != 0:
            raise RuntimeError("".join(stderr_lines).strip() or f"Claude Code exited with {return_code}")
    finally:
        if process.poll() is None:
            process.kill()


