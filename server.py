class GenerationHandler(SimpleHTTPRequestHandler):
    server_version = "GenerationEngine/3"
    protocol_version = "HTTP/1.0"
    extensions_map = {
        **SimpleHTTPRequestHandler.extensions_map,
        ".html": "text/html; charset=utf-8",
        ".js": "application/javascript; charset=utf-8",
        ".css": "text/css; charset=utf-8",
        ".json": "application/json; charset=utf-8",
    }

    def translate_path(self, path: str) -> str:
        parsed = urllib.parse.urlparse(path)
        clean = parsed.path.lstrip("/") or "index.html"
        safe = Path(clean)
        if any(part == ".." for part in safe.parts):
            return str(WEB_DIR / "index.html")
        target = WEB_DIR / safe
        if target.is_dir():
            target = target / "index.html"
        if not target.exists() and not parsed.path.startswith("/api/"):
            target = WEB_DIR / "index.html"
        return str(target)

    def log_message(self, fmt: str, *args: Any) -> None:
        console_log("%s - %s" % (self.address_string(), fmt % args))

    def read_json_body(self) -> dict[str, Any]:
        length = int(self.headers.get("content-length", "0") or "0")
        if not length:
            return {}
        raw = self.rfile.read(length).decode("utf-8")
        return json.loads(raw or "{}")

    def send_json(self, data: Any, status: int = 200) -> None:
        payload = json.dumps(data, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self.send_header("content-type", "application/json; charset=utf-8")
        self.send_header("content-length", str(len(payload)))
        self.send_header("cache-control", "no-store")
        self.end_headers()
        self.wfile.write(payload)

    def send_error_json(self, status: int, message: str, details: str | None = None) -> None:
        self.send_json({"error": message, "details": details}, status=status)

    def do_GET(self) -> None:
        try:
            parsed = urllib.parse.urlparse(self.path)
            if parsed.path.startswith("/api/"):
                self.route_get(parsed)
            else:
                super().do_GET()
        except Exception as exc:
            self.send_error_json(500, str(exc), traceback.format_exc())

    def do_POST(self) -> None:
        try:
            parsed = urllib.parse.urlparse(self.path)
            if parsed.path == "/api/transcribe":
                self.route_transcribe()
            elif re.fullmatch(r"/api/research/[^/]+/sources/upload", parsed.path):
                self.route_research_upload(parsed)
            else:
                self.route_post(parsed, self.read_json_body())
        except urllib.error.HTTPError as exc:
            self.send_error_json(exc.code, exc.read().decode("utf-8", errors="replace"))
        except Exception as exc:
            self.send_error_json(500, str(exc), traceback.format_exc())

    def do_PUT(self) -> None:
        try:
            parsed = urllib.parse.urlparse(self.path)
            self.route_put(parsed, self.read_json_body())
        except Exception as exc:
            self.send_error_json(500, str(exc), traceback.format_exc())

    def do_DELETE(self) -> None:
        try:
            parsed = urllib.parse.urlparse(self.path)
            self.route_delete(parsed, self.read_json_body())
        except FileNotFoundError as exc:
            self.send_error_json(404, str(exc))
        except PermissionError as exc:
            self.send_error_json(423, str(exc))
        except ValueError as exc:
            self.send_error_json(400, str(exc))
        except Exception as exc:
            self.send_error_json(500, str(exc), traceback.format_exc())

    def route_transcribe(self) -> None:
        length = int(self.headers.get("content-length", "0") or "0")
        if not length:
            self.send_error_json(400, "No audio was uploaded.")
            return
        raw = self.rfile.read(length)
        content_type = self.headers.get("content-type", "")
        filename = "recording.wav"
        if content_type.startswith("multipart/form-data"):
            audio_bytes, filename = parse_multipart_file(content_type, raw)
        else:
            audio_bytes = raw
        suffix = Path(filename).suffix.lower()
        if suffix not in {".wav", ".webm", ".ogg", ".mp3", ".m4a"}:
            suffix = ".wav"
        TMP_DIR.mkdir(parents=True, exist_ok=True)
        audio_path = TMP_DIR / f"transcribe-{uuid.uuid4().hex}{suffix}"
        audio_path.write_bytes(audio_bytes)
        try:
            transcript = transcribe_audio_file(audio_path)
        except Exception as exc:
            self.send_error_json(503, str(exc))
            return
        self.send_json({"transcript": transcript, "engine": "local-whisper"})

    def route_research_upload(self, parsed: urllib.parse.ParseResult) -> None:
        parts = [urllib.parse.unquote(part) for part in parsed.path.strip("/").split("/")]
        slug = parts[2]
        if not is_research_project(slug):
            self.send_error_json(400, "Uploads to the research source ledger require a research project.")
            return
        length = int(self.headers.get("content-length", "0") or "0")
        raw = self.rfile.read(length)
        fields, files = parse_multipart_form(self.headers.get("content-type", ""), raw)
        uploaded = files.get("file") or next(iter(files.values()), None)
        if not uploaded:
            self.send_error_json(400, "No file was uploaded.")
            return
        filename = str(uploaded.get("filename") or "uploaded-source")
        content = uploaded.get("content") or b""
        suffix = Path(filename).suffix.lower()
        TMP_DIR.mkdir(parents=True, exist_ok=True)
        tmp_path = TMP_DIR / f"upload-{uuid.uuid4().hex}{suffix or '.bin'}"
        tmp_path.write_bytes(content)
        extracted = extract_uploaded_text(tmp_path, filename, str(uploaded.get("content_type") or ""))
        payload = {
            "title": fields.get("title") or Path(filename).stem,
            "type": fields.get("type") or "other",
            "reliability": fields.get("reliability") or "secondary",
            "provenance": "uploaded_file",
        }
        research = create_research_source(slug, payload, original_bytes=content, original_name=filename, extracted_text=extracted)
