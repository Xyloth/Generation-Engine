def derive_claim_readiness(claim: dict[str, Any], people: dict[str, dict[str, Any]]) -> dict[str, Any]:
    updated = dict(claim)
    supporting = updated.get("supporting_sources") or []
    contradicting = updated.get("contradicting_sources") or []
    claim_type = str(updated.get("type") or "fact")
    confidence = str(updated.get("confidence") or "")
    if contradicting:
        confidence = "contradicted"
    elif len(supporting) >= 2 and confidence in {"", "single-sourced", "unsourced"}:
        confidence = "multi-sourced"
    elif len(supporting) == 1 and confidence in {"", "unsourced"}:
        confidence = "single-sourced"
    elif not supporting:
        confidence = "unsourced"
    blockers: list[str] = []
    if confidence == "unsourced":
        blockers.append("no_supporting_source")
    if contradicting:
        blockers.append("has_contradicting_sources")
    high_risk_subject = False
    for ref in updated.get("subject_refs") or []:
        person = people.get(str(ref)) or {}
        if person.get("living") is True or str(person.get("living")).lower() == "true":
            if str(person.get("defamation_risk", "")).lower() == "high" or str(person.get("status", "")).lower() in {"suspect", "witness"}:
                high_risk_subject = True
    if high_risk_subject and claim_type in {"allegation", "rumor", "inference"}:
        blockers.append("living_person_allegation_requires_stronger_sourcing")
    if claim_type == "allegation" and not any("court" in str(src.get("source_id", "")).lower() or "charging" in str(src.get("excerpt", "")).lower() for src in supporting):
        blockers.append("allegation_without_court_record_source")
    if blockers and ("no_supporting_source" in blockers or "has_contradicting_sources" in blockers):
        readiness = "blocked"
    elif blockers:
        readiness = "needs_review"
    elif confidence in {"confirmed", "multi-sourced"}:
        readiness = "ready"
    else:
        readiness = "qualified"
    updated["confidence"] = confidence
    updated["publish_readiness"] = readiness
    updated["publish_blockers"] = blockers
    updated.setdefault("created_at", now_iso())
    updated["last_modified"] = now_iso()
    return updated


def strip_html_to_text(raw: str) -> str:
    raw = re.sub(r"(?is)<(script|style|noscript|svg).*?</\1>", " ", raw)
    raw = re.sub(r"(?is)<br\s*/?>", "\n", raw)
    raw = re.sub(r"(?is)</p\s*>", "\n\n", raw)
    raw = re.sub(r"(?is)<[^>]+>", " ", raw)
    raw = html.unescape(raw)
    return re.sub(r"[ \t]+\n", "\n", re.sub(r"\n{3,}", "\n\n", re.sub(r"[ \t]{2,}", " ", raw))).strip()


def fetch_url_text(url: str) -> tuple[str, str, bytes]:
    req = urllib.request.Request(
        url,
        headers={"user-agent": "GenerationEngine/1.0 local research tool"},
        method="GET",
    )
    with urllib.request.urlopen(req, timeout=60) as response:
        data = response.read()
        content_type = response.headers.get("content-type", "")
    decoded = data.decode("utf-8", errors="replace")
    title_match = re.search(r"(?is)<title[^>]*>(.*?)</title>", decoded)
    title = strip_html_to_text(title_match.group(1)).strip() if title_match else url
    if "html" in content_type or decoded.lstrip().startswith("<"):
        return title or url, strip_html_to_text(decoded), data
    return title or url, decoded.strip(), data


def youtube_video_id(url: str) -> str | None:
    match = re.search(r"(?:v=|youtu\.be/|shorts/)([A-Za-z0-9_-]{8,})", url)
    return match.group(1) if match else None


def fetch_youtube_transcript(url: str) -> tuple[str, str, bytes]:
    video_id = youtube_video_id(url)
    if not video_id:
        raise ValueError("Could not read a YouTube video id from the URL.")
    yt_dlp = shutil.which("yt-dlp") or shutil.which("youtube-dl")
    if yt_dlp:
        TMP_DIR.mkdir(parents=True, exist_ok=True)
        base = TMP_DIR / f"yt-{uuid.uuid4().hex}"
        completed = subprocess.run(
            [yt_dlp, "--skip-download", "--write-auto-subs", "--write-subs", "--sub-lang", "en", "--sub-format", "vtt", "-o", str(base), url],
            capture_output=True,
            text=True,
            timeout=180,
            encoding="utf-8",
            errors="replace",
            **hidden_subprocess_kwargs(),
        )
        files = list(TMP_DIR.glob(base.name + "*.vtt"))
        if completed.returncode == 0 and files:
            text = "\n".join(strip_vtt(read_text(path)) for path in files)
            return f"YouTube transcript {video_id}", text.strip(), text.encode("utf-8")
    transcript_url = f"https://video.google.com/timedtext?lang=en&v={urllib.parse.quote(video_id)}"
    try:
        with urllib.request.urlopen(transcript_url, timeout=30) as response:
            raw = response.read()
        text = strip_html_to_text(raw.decode("utf-8", errors="replace"))
        if text:
            return f"YouTube transcript {video_id}", text, raw
    except Exception:
        pass
    placeholder = f"Transcript unavailable for {url}. Add captions, upload audio, or paste the transcript manually."
    return f"YouTube source {video_id}", placeholder, placeholder.encode("utf-8")


def strip_vtt(text: str) -> str:
    lines = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped == "WEBVTT" or "-->" in stripped or stripped.isdigit():
            continue
        lines.append(re.sub(r"<[^>]+>", "", stripped))
    return "\n".join(lines)


def extract_uploaded_text(path: Path, original_name: str, content_type: str) -> str:
    suffix = path.suffix.lower()
    if suffix in {".txt", ".md", ".markdown", ".csv", ".json", ".html", ".htm"} or content_type.startswith("text/"):
        raw = path.read_bytes().decode("utf-8", errors="replace")
        return strip_html_to_text(raw) if suffix in {".html", ".htm"} else raw
    if suffix == ".pdf":
        text = extract_pdf_text(path)
        return text or f"[TEXT EXTRACTION NEEDED: PDF '{original_name}' was stored, but no local PDF text extractor was available.]"
    if suffix in {".wav", ".webm", ".ogg", ".mp3", ".m4a"}:
        try:
            return transcribe_audio_file(path)
        except Exception as exc:
            return f"[TRANSCRIPTION NEEDED: audio '{original_name}' was stored, but local Whisper failed: {exc}]"
    if suffix in {".png", ".jpg", ".jpeg", ".tif", ".tiff", ".bmp"}:
        text = extract_image_text(path)
        return text or f"[OCR NEEDED: image '{original_name}' was stored, but no local OCR engine was available.]"
    return f"[ORIGINAL STORED: '{original_name}'. Paste extracted text or notes into this source.]"


def extract_pdf_text(path: Path) -> str:
    try:
        import fitz  # type: ignore

        doc = fitz.open(str(path))
        return "\n\n".join(page.get_text() for page in doc).strip()
    except Exception:
        pass
    try:
        from pypdf import PdfReader  # type: ignore

        reader = PdfReader(str(path))
        return "\n\n".join(page.extract_text() or "" for page in reader.pages).strip()
    except Exception:
        pass
    pdftotext = shutil.which("pdftotext")
    bundled_pdftotext = find_poppler_tool("pdftotext.exe")
    if bundled_pdftotext:
        pdftotext = bundled_pdftotext
    if pdftotext:
        completed = subprocess.run([pdftotext, str(path), "-"], capture_output=True, text=True, timeout=120, encoding="utf-8", errors="replace", **hidden_subprocess_kwargs())
        if completed.returncode == 0:
            text = completed.stdout.strip()
            if text:
                return text
    return ocr_pdf_pages(path)


def ocr_pdf_pages(path: Path, max_pages: int = 12) -> str:
    pdftoppm = find_poppler_tool("pdftoppm.exe") or shutil.which("pdftoppm")
    tesseract = find_tesseract_executable()
    if not pdftoppm or not tesseract:
        return ""
    out_dir = TMP_DIR / f"pdf-ocr-{uuid.uuid4().hex}"
    out_dir.mkdir(parents=True, exist_ok=True)
    prefix = out_dir / "page"
    completed = subprocess.run(
        [pdftoppm, "-f", "1", "-l", str(max_pages), "-r", "220", "-png", str(path), str(prefix)],
        capture_output=True,
        text=True,
        timeout=180,
        encoding="utf-8",
        errors="replace",
        **hidden_subprocess_kwargs(),
    )
    if completed.returncode != 0:
        return ""
    texts = []
    for image_path in sorted(out_dir.glob("page-*.png")):
        text = extract_image_text(image_path)
        if text:
            texts.append(text)
    try:
        shutil.rmtree(out_dir)
    except OSError:
        pass
    return "\n\n".join(texts).strip()


def extract_image_text(path: Path) -> str:
    tesseract = find_tesseract_executable()
