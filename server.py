def mock_revise(chapter: str, request_text: str) -> Iterable[str]:
    revised = chapter
    lower = request_text.lower()
    if "cut" in lower:
        target = request_text.lower().split("cut", 1)[1].strip().strip(".")
        words = [w for w in re.findall(r"[a-zA-Z]+", target) if len(w) > 3][:4]
        paragraphs = []
        for paragraph in revised.split("\n\n"):
            paragraph_lower = paragraph.lower()
            if words and sum(1 for word in words if word.lower() in paragraph_lower) >= max(1, min(2, len(words))):
                continue
            paragraphs.append(paragraph)
        revised = "\n\n".join(paragraphs)
    if "sharper" in lower or "dialog" in lower or "dialogue" in lower:
        revised = revised.replace('"I picked a place where nobody lingers."', '"Nobody lingers here."')
        revised = revised.replace('"You still have it."', '"You kept it."')
    if "defiant" in lower:
        revised = revised.rstrip() + "\n\nShe did not step back. Let them count that, too.\n"
    if revised == chapter:
        revised = chapter.rstrip() + f"\n\n[Local revision note: apply this request with Claude when the API key is available: {request_text.strip()}]\n"
    for i in range(0, len(revised), 180):
        yield revised[i : i + 180]
        time.sleep(0.01)


