def create_research_source(slug: str, payload: dict[str, Any], original_bytes: bytes | None = None, original_name: str | None = None, extracted_text: str | None = None) -> dict[str, Any]:
    book = book_dir(slug)
    ensure_research_dirs(book)
    root = research_dir(book)
    source_id = next_research_id(root / "sources", "src")
    provenance = str(payload.get("provenance") or payload.get("kind") or "clipboard_paste")
    source_type = str(payload.get("type") or "other")
    reliability = str(payload.get("reliability") or "secondary")
    url = str(payload.get("url") or "").strip()
    title = str(payload.get("title") or "").strip()
    text = str(extracted_text if extracted_text is not None else payload.get("text") or "").strip()
    original_rel = ""
    raw_bytes = original_bytes
    if url and not text:
        if "youtube.com" in url or "youtu.be" in url:
            title, text, raw_bytes = fetch_youtube_transcript(url)
            provenance = "youtube_transcript"
            source_type = "broadcast"
        else:
            title, text, raw_bytes = fetch_url_text(url)
            provenance = "url_fetch"
    if not title:
        title = clean_title_from_markdown(text, "Untitled source")
    if raw_bytes is None:
        raw_bytes = text.encode("utf-8")
    if original_name or url or raw_bytes:
        suffix = Path(original_name or urllib.parse.urlparse(url).path or "source.txt").suffix
        if not suffix:
            suffix = ".txt"
        original_name = original_name or f"{safe_file_stem(title, source_id)}{suffix}"
        original_safe = f"{source_id}-{safe_file_stem(Path(original_name).stem, 'original')}{suffix.lower()}"
        original_path = root / "originals" / original_safe
        original_path.write_bytes(raw_bytes)
        original_rel = f"originals/{original_safe}"
    checksum = checksum_bytes(raw_bytes)
    extraction = extract_research_with_ai(slug, title, text, source_id)
    entity_refs = [create_or_update_entity(book, entity, source_id) for entity in extraction.get("entities", []) if isinstance(entity, dict)]
    entity_refs = [ref for ref in entity_refs if ref]
    claims = load_claims(book)
    added_claims: list[dict[str, Any]] = []
    for claim in extraction.get("claims", [])[:20]:
        if not isinstance(claim, dict):
            continue
        claim["id"] = next_claim_id(claims)
        claim.setdefault("supporting_sources", [{"source_id": source_id, "excerpt": str(claim.get("text", ""))[:800]}])
        claim.setdefault("contradicting_sources", [])
        claim.setdefault("subject_refs", [])
        claim.setdefault("event_ref", "")
        claim.setdefault("type", "fact")
        claim.setdefault("confidence", "single-sourced")
        claim.setdefault("notes", "Auto-extracted from source; review before publication.")
        claims.append(claim)
        added_claims.append(claim)
    claims = save_claims(book, claims)
    added_ids = [claim["id"] for claim in added_claims]
    append_timeline_events(book, [event for event in extraction.get("events", []) if isinstance(event, dict)], source_id, added_ids)
    meta = {
        "id": source_id,
        "title": title,
        "type": source_type,
        "url": url,
        "file": original_rel,
        "accessed": time.strftime("%Y-%m-%d"),
        "author": str(payload.get("author") or ""),
        "agency": str(payload.get("agency") or ""),
        "provenance": provenance,
        "reliability": reliability,
        "checksum": checksum,
        "verified_by": "",
        "verified_at": "",
        "entity_refs": entity_refs,
        "claim_refs": added_ids,
    }
    excerpts = "\n\n".join(f"> {str(excerpt).strip()}" for excerpt in extraction.get("excerpts", [])[:8] if str(excerpt).strip())
    body = (
        f"# {title}\n\n"
        "## AI-generated summary\n\n"
        f"{str(extraction.get('summary') or '').strip()}\n\n"
        "## Exact excerpts\n\n"
        f"{excerpts or '> No exact excerpts were extracted automatically. Review the original/source text.'}\n\n"
        "## Extracted text\n\n"
        f"{text[:120000]}\n\n"
        "## User notes\n\n"
    )
    write_text(root / "sources" / f"{source_id}.md", frontmatter_markdown(meta, body))
    detect_claim_contradictions(book)
    return load_research(slug)


def detect_claim_contradictions(book: Path) -> None:
    claims = load_claims(book)
    by_subject: dict[str, list[dict[str, Any]]] = {}
    for claim in claims:
        key = " ".join(sorted(str(ref) for ref in claim.get("subject_refs") or [])) or "general"
        by_subject.setdefault(key, []).append(claim)
    for group in by_subject.values():
        for claim in group:
            text = str(claim.get("text", "")).lower()
            contradictions = claim.setdefault("contradicting_sources", [])
            for other in group:
                if other is claim:
                    continue
                other_text = str(other.get("text", "")).lower()
                if any(word in text and word in other_text for word in ("not", "never", "denied", "midnight", "11:30")) and text != other_text:
                    src = (other.get("supporting_sources") or [{}])[0]
                    note = {"source_id": src.get("source_id", ""), "excerpt": other.get("text", ""), "note": f"Potential conflict with {other.get('id')}"}
                    if note not in contradictions:
                        contradictions.append(note)
    save_claims(book, claims)


