def extract_claude_stream_delta(event: dict[str, Any], prior_text: str) -> tuple[str, str]:
    event_type = event.get("type")
    if event_type == "content_block_delta":
        delta = event.get("delta", {})
        if isinstance(delta, dict) and delta.get("type") == "text_delta":
            text = str(delta.get("text", ""))
            return text, prior_text + text
    if event_type == "assistant":
        message = event.get("message", {})
        content = message.get("content", []) if isinstance(message, dict) else event.get("content", [])
        text = ""
        if isinstance(content, list):
            for block in content:
                if isinstance(block, dict) and block.get("type") == "text":
                    text += str(block.get("text", ""))
        elif isinstance(content, str):
            text = content
        if text:
            if text.startswith(prior_text):
                return text[len(prior_text) :], text
            return text, prior_text + text
    if event_type == "text":
        text = str(event.get("text", ""))
        return text, prior_text + text
    if event_type == "result" and isinstance(event.get("result"), str):
        text = event["result"]
        if text.startswith(prior_text):
            return text[len(prior_text) :], text
        return text, prior_text + text
    return "", prior_text


