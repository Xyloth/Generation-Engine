def anthropic_message_for_import(prompt: str) -> str:
    if not CONFIG.api_key:
        raise RuntimeError("Missing ANTHROPIC_API_KEY")
    preflight = get_preflight()
    if active_mode() == "api" and not preflight.api_ok:
        raise RuntimeError(preflight.api_message)
    body = {
        "model": CONFIG.utility_model,
        "max_tokens": 10000,
        "system": [{"type": "text", "text": IMPORT_SYSTEM}],
        "messages": [{"role": "user", "content": prompt}],
    }
    req = urllib.request.Request(
        "https://api.anthropic.com/v1/messages",
        data=json.dumps(body).encode("utf-8"),
        headers={
            "content-type": "application/json",
            "x-api-key": CONFIG.api_key,
            "anthropic-version": "2023-06-01",
        },
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=600) as response:
        data = json.loads(response.read().decode("utf-8"))
    return "".join(block.get("text", "") for block in data.get("content", []) if block.get("type") == "text")


def find_open_port(start: int) -> int:
    port = start
    while port < start + 50:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
            probe.settimeout(0.25)
            if probe.connect_ex(("127.0.0.1", port)) == 0:
                port += 1
                continue
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            try:
                sock.bind(("127.0.0.1", port))
                return port
            except OSError:
                port += 1
    raise RuntimeError("No open local port found")


